// User-interface translations. Keys are the English text, so English needs
// no table and a missing Italian entry falls back to English. A test checks
// that every key used in web/js has an Italian entry, and no entry is unused.

let lang = 'en';

export function detectLang() {
  return (navigator.language || 'en').toLowerCase().startsWith('it') ? 'it' : 'en';
}

export function setLang(value) {
  lang = value === 'it' ? 'it' : 'en';
  document.documentElement.lang = lang;
}

export function getLang() {
  return lang;
}

/** Translates `key` and fills `{name}` placeholders from `vars`. */
export function t(key, vars) {
  let text = lang === 'it' && Object.hasOwn(IT, key) ? IT[key] : key;
  if (vars) text = text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
  return text;
}

